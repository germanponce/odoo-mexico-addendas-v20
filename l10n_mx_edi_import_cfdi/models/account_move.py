    def _compute_price_unit(self):
        for line in self:
            if not line.move_id.l10n_mx_edi_imported_from_xml:
                super(AccountMoveLine, line)._compute_price_unit()

    @api.depends('product_id', 'journal_id')
    def _compute_name(self):
        for line in self:
            if not line.move_id.l10n_mx_edi_imported_from_xml:
                super(AccountMoveLine, line)._compute_name()

    @api.depends('product_id', 'product_uom_id')
    def _compute_tax_ids(self):
        for line in self:
            if not line.move_id.l10n_mx_edi_imported_from_xml:
                super(AccountMoveLine, line)._compute_tax_ids()
